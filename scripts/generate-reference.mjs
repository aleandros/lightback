// Generate public reference tables directly from the SDK's TypeScript declarations.
import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const write = (path, text) => writeFileSync(new URL(path, root), text);
const parse = (path) => ts.createSourceFile(path, read(path), ts.ScriptTarget.Latest, true);
const cell = (text) => text.replace(/\s+/g, ' ').replace(/\|/g, '&#124;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/`/g, '&#96;');
const code = (text) => `<code>${cell(text)}</code>`;
const source = parse('packages/core/src/types.ts');
const names = ['FeedbackPayload', 'ElementSelection', 'ElementSummary', 'ElementContext', 'ComponentInfo', 'SourceLocation', 'Rect', 'AttachmentRef', 'Env', 'ConsoleEntry', 'ErrorEntry', 'NetworkEntry', 'Breadcrumb'];
let payload = `# Payload reference

<!-- Generated by scripts/generate-reference.mjs. Edit types.ts or the generator. -->

The wire format is version **1**. The tables below are generated from \`packages/core/src/types.ts\` by \`pnpm --filter docs build\`. A question mark marks an optional field. These are TypeScript declarations, not runtime validation; validate incoming data in your receiver.

\`createdAt\` is an ISO 8601 string. Collector timestamps (\`t\`) and network durations are milliseconds; timestamps use Unix epoch time. Rectangles and page dimensions use CSS pixels. \`rect\` is viewport-relative; \`docRect\` includes the scroll offset. Screenshot pixels may differ by device pixel ratio.

\`attachments\` contains metadata only. Binary files travel as separate multipart fields named by \`name\`; a selection's \`crop\` points to one of those fields. A custom \`send\` receives an additional array of \`Attachment\` objects with a \`blob: Blob\` field. See [Backend](./backend.md).

Component names, sources and props depend on what the host framework exposes. Missing debug metadata is normal in production. \`note.transcript\` can be supplied through the core draft API; the widget has no voice recorder.

Default ring-buffer limits are 200 console entries, 50 errors, 100 network entries and 100 breadcrumbs. Request/response bodies are disabled unless explicitly enabled, and then only captured for same-origin requests. Strings captured by collectors and element inspection are bounded; application context should be kept small and safe by the host.
`;
for (const name of names) {
  const node = source.statements.find((s) => ts.isInterfaceDeclaration(s) && s.name.text === name);
  if (!node) throw new Error(`Missing interface ${name}`);
  payload += `\n## ${name}\n\n| Field | Type | Description |\n| --- | --- | --- |\n`;
  for (const member of node.members) {
    const comment = (member.jsDoc ?? []).map((doc) => typeof doc.comment === 'string' ? doc.comment : '').join(' ');
    payload += `| ${code(member.name.getText(source) + (member.questionToken ? '?' : ''))} | ${code(member.type.getText(source))} | ${cell(comment)} |\n`;
  }
}
const level = source.statements.find((s) => ts.isTypeAliasDeclaration(s) && s.name.text === 'Level');
payload += `\n## Level\n\n${code(level.type.getText(source))}\n`;
write('docs/guide/payload.md', payload);
const stringsSource = parse('packages/widget/src/strings.ts');
const defaults = stringsSource.statements.flatMap((s) => ts.isVariableStatement(s) ? [...s.declarationList.declarations] : []).find((s) => s.name.getText(stringsSource) === 'defaultStrings');
let strings = `# String reference\n\n<!-- Generated by scripts/generate-reference.mjs. Edit strings.ts or the generator. -->\n\nEvery key in the exported \`defaultStrings\` table. See [Texts and i18n](./texts-and-i18n.md) for usage. Function defaults show their arguments so you can implement your locale's plural rules.\n\n| Key | English default |\n| --- | --- |\n`;
for (const prop of defaults.initializer.properties) strings += `| ${code(prop.name.getText(stringsSource))} | ${code(prop.initializer.getText(stringsSource))} |\n`;
write('docs/guide/strings-reference.md', strings);
console.log('Generated payload and string references.');
